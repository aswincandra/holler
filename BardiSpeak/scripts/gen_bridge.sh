#!/bin/zsh
# Compile bridge.js into the binary as a Swift string, so the code signature covers it
# and nobody can swap the file inside the installed app. Runs from build_app.sh and
# as an Xcode build step.
set -euo pipefail
cd "$(dirname "$0")/.."
if grep -q '"""##' Resources/bridge.js; then echo 'bridge.js contains """## (breaks the raw string)'; exit 1; fi
mkdir -p Generated
{ print -r -- '// Generated by scripts/gen_bridge.sh from Resources/bridge.js. Do not edit.'
  print -r -- 'let bridgeJS = ##"""'
  cat Resources/bridge.js
  print -r -- '"""##'; } > Generated/BridgeJS.swift.tmp
# Only touch the file when it changed, so Xcode doesn't rebuild for nothing.
if cmp -s Generated/BridgeJS.swift.tmp Generated/BridgeJS.swift; then rm Generated/BridgeJS.swift.tmp
else mv Generated/BridgeJS.swift.tmp Generated/BridgeJS.swift; fi
